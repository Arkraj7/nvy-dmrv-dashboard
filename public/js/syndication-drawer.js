  function tryUnlock() {
    var input = document.getElementById('synd-pass');
    var err = document.getElementById('synd-err');
    if (!input) return;
    var value = input.value;
    if (!value) { err.textContent = 'Enter the desk passphrase.'; return; }
    err.textContent = '';
    sha256hex(value).then(function (hash) {
      if (hash === PASS_SHA256) {
        deskHash = hash;
        setUnlocked(true, hash);
        input.value = '';
        showContent();
        loadAssets();
        var firstBtn = contentEl.querySelector('button');
        if (firstBtn) firstBtn.focus();
      } else {
        err.textContent = 'Passphrase not recognised.';
        input.select();
      }
    }).catch(function () {
      err.textContent = 'Secure context unavailable in this browser - open the site over HTTPS.';
    });
  }

