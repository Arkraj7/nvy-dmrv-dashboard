  function openDrawer() {
    buildDom();
    if (root.classList.contains('is-open')) return;
    lastFocus = document.activeElement;
    root.classList.add('is-open');
    root.setAttribute('aria-hidden', 'false');
    document.documentElement.classList.add('synd-open');
    deskHash = storedHash();
    if (unlockKey() && deskHash) {
      showContent();
      loadAssets();
      var first = contentEl.querySelector('button');
      if (first) first.focus();
    } else {
      if (unlockKey() && !deskHash) setUnlocked(false);
      showGate();
      var input = document.getElementById('synd-pass');
      if (input) input.focus();
    }
  }

  function closeDrawer() {
    if (!root || !root.classList.contains('is-open')) return;
    root.classList.remove('is-open');
    root.setAttribute('aria-hidden', 'true');
    document.documentElement.classList.remove('synd-open');
    if (lastFocus && lastFocus.focus) lastFocus.focus();
  }

  /* --------------------------------------------------------------- triggers */

  function initTriggers() {
    document.addEventListener('keydown', function (e) {
      var key = e.key || '';
      if ((e.ctrlKey || e.metaKey) && e.shiftKey && (key === 'U' || key === 'u' || e.code === 'KeyU')) {
        e.preventDefault();
        openDrawer();
      }
    });

    document.addEventListener('click', function (e) {
      var trigger = e.target && e.target.closest ? e.target.closest('[data-syndication-open]') : null;
      if (trigger) { e.preventDefault(); openDrawer(); }
    });

    window.addEventListener('hashchange', function () {
      if (location.hash === '#syndication') openDrawer();
    });
  }

  function init() {
    buildStyles();
    initTriggers();
    var byBodyAttr = document.body && document.body.hasAttribute('data-syndication-open');
    var byHash = location.hash === '#syndication';
    var byQuery = /[?&]syndication=1(?:&|$)/.test(location.search);
    if (byBodyAttr || byHash || byQuery) {
      /* give the page a beat to paint behind the drawer */
      setTimeout(openDrawer, 60);
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
