def main():
    india = json.loads(JOBS_PATH.read_text(encoding="utf-8"))
    global_jobs = json.loads(GLOBAL_PATH.read_text(encoding="utf-8"))
    existing_ids = {r.get("id") for r in india + global_jobs}

    added_india = 0
    for rec in INDIA_RECORDS:
        if rec["id"] in existing_ids:
            print(f"SKIP (exists): {rec['id']}")
            continue
        india.append(rec)
        added_india += 1
        print(f"ADD: {rec['id']}")

    added_global = 0
    for rec in GLOBAL_RECORDS:
        if rec["id"] in existing_ids:
            print(f"SKIP (exists): {rec['id']}")
            continue
        global_jobs.append(rec)
        added_global += 1
        print(f"ADD: {rec['id']}")

    JOBS_PATH.write_text(json.dumps(india, ensure_ascii=False, indent=2), encoding="utf-8")
    GLOBAL_PATH.write_text(json.dumps(global_jobs, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nAdded {added_india} India + {added_global} global. Total India: {len(india)}, Global: {len(global_jobs)}")


if __name__ == "__main__":
    main()
