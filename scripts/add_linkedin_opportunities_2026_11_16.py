def main() -> int:
    # India
    path = PUBLIC / "jobs.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    existing = {r["id"] for r in data}
    added = 0
    for d in INDIA:
        if d["id"] in existing:
            print(f"SKIP (exists): {d['id']}")
            continue
        data.append(make_record(d))
        added += 1
        print(f"ADD (India): {d['id']}")
    if added:
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"jobs.json: +{added}")

    # Global
    path = PUBLIC / "global_jobs.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    existing = {r["id"] for r in data}
    added = 0
    for d in GLOBAL:
        if d["id"] in existing:
            print(f"SKIP (exists): {d['id']}")
            continue
        data.append(make_record(d))
        added += 1
        print(f"ADD (Global): {d['id']}")
    if added:
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"global_jobs.json: +{added}")

    return 0


