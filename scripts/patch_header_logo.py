"""Inject the circular Urban Forest Park emblem (.ufp-header-logo) into the
hand-maintained pages:

  * public/index.html          (inside the .brand anchor)
  * public/dashboard.html      (Tailwind nav, left of the Nagar Van logo)
  * public/privacy.html        (legal topbar wordmark)
  * public/terms.html          (legal topbar wordmark)
  * public/cookies.html        (legal topbar wordmark)
  * public/accessibility.html  (legal topbar wordmark)
  * public/unsubscribe.html    (legal topbar wordmark)

The SEO hub pages are generated by scripts/build_seo_pages.py and
scripts/seo_portals.py, which already emit the emblem.

Idempotent: pages that already contain 'ufp-header-logo' are skipped.
Abort-safe: a page whose anchor markup cannot be found is reported and left
untouched (the script never writes partial output).
"""
from __future__ import annotations

import logging
import re
import sys
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger("patch_header_logo")

REPO_ROOT = Path(__file__).resolve().parent.parent
PUBLIC = REPO_ROOT / "public"

IMG = (
    '<img src="/assets/images/Logo_UFF.png" alt="Urban Forest Park emblem" '
    'class="ufp-header-logo" width="38" height="38" loading="eager" decoding="async" />'
)
IMG_DASHBOARD = (
    '<img src="/assets/images/Logo_UFF.png" alt="Urban Forest Park emblem" '
    'class="ufp-header-logo" width="38" height="38" loading="eager" decoding="async" '
    'style="width:38px;height:38px;min-width:38px;border-radius:50%;object-fit:cover;'
    'border:1.5px solid rgba(16,185,129,0.35);background:#FFFDF9;margin-right:10px;" />'
)

BRAND_PATTERN = re.compile(
    r'(<a class="brand" href="/"[^>]*>)(\s*)'
    r'(<span class="brand-word">)',
    re.S,
)

DASHBOARD_ANCHOR = (
    '                <div class="flex items-center gap-3">\n'
    '                    <div class="w-14 h-14 flex items-center justify-center" role="img" aria-label="Nagar Van logo">'
)
DASHBOARD_REPLACEMENT = (
    '                <div class="flex items-center gap-3">\n'
    '                    ' + IMG_DASHBOARD + '\n'
    '                    <div class="w-14 h-14 flex items-center justify-center" role="img" aria-label="Nagar Van logo">'
)

LEGAL_PATTERN = re.compile(
    r'(<a class="legal-wordmark" href="[^"]*">)\s*'
    r'<span class="lw-name">(.*?)</span>\s*'
    r'<span class="lw-sub">(.*?)</span>',
    re.S,
)


def legal_replacement(match: "re.Match[str]") -> str:
    return (
        match.group(1) + "\n"
        + "        " + IMG + "\n"
        + '        <span class="lw-text">\n'
        + '          <span class="lw-name">' + match.group(2) + '</span>\n'
        + '          <span class="lw-sub">' + match.group(3) + '</span>\n'
        + '        </span>'
    )


def patch_brand_page(path: Path) -> str:
    html = path.read_text(encoding="utf-8")
    if "ufp-header-logo" in html:
        return "skipped (logo already present)"
    new_html, count = BRAND_PATTERN.subn(
        lambda m: m.group(1) + m.group(2) + IMG + "\n" + m.group(2) + m.group(3),
        html,
        count=1,
    )
    if count != 1:
        return "ANCHOR NOT FOUND - left untouched"
    path.write_text(new_html, encoding="utf-8")
    return "patched"


def patch_dashboard(path: Path) -> str:
    html = path.read_text(encoding="utf-8")
    if "ufp-header-logo" in html:
        return "skipped (logo already present)"
    if DASHBOARD_ANCHOR not in html:
        return "ANCHOR NOT FOUND - left untouched"
    path.write_text(html.replace(DASHBOARD_ANCHOR, DASHBOARD_REPLACEMENT, 1), encoding="utf-8")
    return "patched"


def patch_legal(path: Path) -> str:
    html = path.read_text(encoding="utf-8")
    if "ufp-header-logo" in html:
        return "skipped (logo already present)"
    new_html, count = LEGAL_PATTERN.subn(legal_replacement, html, count=1)
    if count != 1:
        return "ANCHOR NOT FOUND - left untouched"
    path.write_text(new_html, encoding="utf-8")
    return "patched"


def main() -> int:
    targets = [
        (PUBLIC / "index.html", patch_brand_page),
        (PUBLIC / "dashboard.html", patch_dashboard),
        (PUBLIC / "privacy.html", patch_legal),
        (PUBLIC / "terms.html", patch_legal),
        (PUBLIC / "cookies.html", patch_legal),
        (PUBLIC / "accessibility.html", patch_legal),
        (PUBLIC / "unsubscribe.html", patch_legal),
    ]
    failures = 0
    for path, patcher in targets:
        if not path.exists():
            log.warning("%s: missing", path.name)
            failures += 1
            continue
        result = patcher(path)
        if "ANCHOR NOT FOUND" in result:
            failures += 1
        log.info("%s: %s", path.name, result)
    log.info("Done (%d failure(s)).", failures)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
